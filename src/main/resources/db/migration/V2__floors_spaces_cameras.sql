-- Floor maps that providers draw in the 3D editor: one floor per building in the website for now,
-- but the table allows many (one row per level). All sizes and positions are in metres,
-- measured from the floor's corner: x along the width, z along the length.

CREATE TABLE floors (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id BIGINT NOT NULL REFERENCES buildings (id) ON DELETE CASCADE,
    level       INT NOT NULL DEFAULT 0,
    name        VARCHAR(50) NOT NULL,
    width_m     DOUBLE PRECISION NOT NULL CHECK (width_m > 0),
    length_m    DOUBLE PRECISION NOT NULL CHECK (length_m > 0),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_floors_building_level UNIQUE (building_id, level)
);

-- A wall is a straight segment from (x1, z1) to (x2, z2).
CREATE TABLE floor_walls (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id    BIGINT NOT NULL REFERENCES floors (id) ON DELETE CASCADE,
    x1          DOUBLE PRECISION NOT NULL,
    z1          DOUBLE PRECISION NOT NULL,
    x2          DOUBLE PRECISION NOT NULL,
    z2          DOUBLE PRECISION NOT NULL,
    thickness_m DOUBLE PRECISION NOT NULL CHECK (thickness_m > 0)
);

CREATE INDEX idx_floor_walls_floor ON floor_walls (floor_id);

-- A column is a box centred on (x, z).
CREATE TABLE floor_columns (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id BIGINT NOT NULL REFERENCES floors (id) ON DELETE CASCADE,
    x        DOUBLE PRECISION NOT NULL,
    z        DOUBLE PRECISION NOT NULL,
    width_m  DOUBLE PRECISION NOT NULL CHECK (width_m > 0),
    depth_m  DOUBLE PRECISION NOT NULL CHECK (depth_m > 0)
);

CREATE INDEX idx_floor_columns_floor ON floor_columns (floor_id);

-- A camera is mounted on a wall or a column. direction_deg: which way it looks, seen from above
-- (0 = towards +x, 90 = towards +z). The device key lets the detector program report occupancy;
-- only its SHA-256 hash is stored.
CREATE TABLE cameras (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id      BIGINT NOT NULL REFERENCES floors (id) ON DELETE CASCADE,
    name          VARCHAR(50) NOT NULL,
    mount         VARCHAR(10) NOT NULL CHECK (mount IN ('WALL', 'COLUMN')),
    x             DOUBLE PRECISION NOT NULL,
    z             DOUBLE PRECISION NOT NULL,
    direction_deg DOUBLE PRECISION NOT NULL,
    key_hash      VARCHAR(64),
    key_created_at TIMESTAMP WITH TIME ZONE,
    last_seen_at  TIMESTAMP WITH TIME ZONE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_cameras_floor ON cameras (floor_id);

-- A parking space (stall), a rectangle centred on (x, z) and turned by rotation_deg.
-- Each space is watched by at most one camera (camera_id). Labels are unique per floor (checked by the app).
CREATE TABLE spaces (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id          BIGINT NOT NULL REFERENCES floors (id) ON DELETE CASCADE,
    label             VARCHAR(20) NOT NULL,
    x                 DOUBLE PRECISION NOT NULL,
    z                 DOUBLE PRECISION NOT NULL,
    width_m           DOUBLE PRECISION NOT NULL CHECK (width_m > 0),
    length_m          DOUBLE PRECISION NOT NULL CHECK (length_m > 0),
    rotation_deg      DOUBLE PRECISION NOT NULL DEFAULT 0,
    camera_id         BIGINT REFERENCES cameras (id) ON DELETE SET NULL,
    status            VARCHAR(10) NOT NULL DEFAULT 'UNKNOWN' CHECK (status IN ('FREE', 'OCCUPIED', 'UNKNOWN')),
    status_changed_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_spaces_floor ON spaces (floor_id);
CREATE INDEX idx_spaces_camera ON spaces (camera_id);

-- Every change of a space's state, as reported by a camera.
CREATE TABLE occupancy_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id    BIGINT NOT NULL REFERENCES spaces (id) ON DELETE CASCADE,
    camera_id   BIGINT REFERENCES cameras (id) ON DELETE SET NULL,
    old_status  VARCHAR(10) NOT NULL,
    new_status  VARCHAR(10) NOT NULL,
    observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
    received_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_occupancy_events_space ON occupancy_events (space_id, observed_at);
