-- Accounts (customers, parking providers, admins) and the parking buildings providers add.
-- Plain SQL that runs on PostgreSQL and on H2 (used by the tests).

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    first_name    VARCHAR(50)  NOT NULL,
    last_name     VARCHAR(50)  NOT NULL,
    phone         VARCHAR(20)  NOT NULL,
    role          VARCHAR(20)  NOT NULL CHECK (role IN ('CUSTOMER', 'PROVIDER', 'ADMIN')),
    status        VARCHAR(20)  NOT NULL CHECK (status IN ('ACTIVE', 'PENDING', 'REJECTED')),
    company_name  VARCHAR(100),
    work_location VARCHAR(200),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    reviewed_at   TIMESTAMP WITH TIME ZONE,
    reviewed_by   BIGINT REFERENCES users (id)
);

CREATE INDEX idx_users_role_status ON users (role, status);

CREATE TABLE buildings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name        VARCHAR(100) NOT NULL,
    latitude    DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude   DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_buildings_provider ON buildings (provider_id);
